def generate(
    docs_path: Path | None = None,
    drive_path: Path | None = None,
    overlay_path: Path | None = None,
    config_path: Path | None = None,
) -> dict[str, str]:
    """Build all output files. Returns {relative_filename: content}."""
    docs_base = load_json(docs_path or DISCOVERY_DIR / "docs-v1.json")
    drive = load_json(drive_path or DISCOVERY_DIR / "drive-v3.json")
    overlay = load_json(overlay_path or OVERLAY_PATH)
    config = load_json(config_path or CONFIG_PATH)

    docs, preview_members, _preview_schemas = merge_overlay(docs_base, overlay)
    docs_schemas = docs.get("schemas", {})
    drive_schemas = drive.get("schemas", {})
    write_mode_available = "writeMode" in docs_schemas.get("WriteControl", {}).get(
        "properties", {}
    )

    base_methods = set(
        docs_base.get("resources", {}).get("documents", {}).get("methods", {})
    )

    modules: dict[str, list[ToolSpec]] = {
        "docs_methods": [],
        "docs_batch_update": [],
        "docs_preview": [],
        "drive_comments": [],
    }

    docs_methods = docs.get("resources", {}).get("documents", {}).get("methods", {})
    for method_name in sorted(docs_methods):
        spec = build_method_tool(
            api_name="docs",
            resource_name="documents",
            resource_attr="documents",
            method_name=method_name,
            method=docs_methods[method_name],
            schemas=docs_schemas,
            preview=method_name not in base_methods,
            service_type="docs",
            read_group="docs_read",
            write_group="docs_write",
            add_fields_param=False,
        )
        spec.module = "docs_methods"
        modules["docs_methods"].append(spec)

    request_members = docs_schemas.get("Request", {}).get("properties", {})
    for member in sorted(request_members):
        preview = member in preview_members
        spec = build_member_tool(
            member,
            request_members[member],
            docs_schemas,
            preview,
            write_mode_available,
            config,
        )
        spec.module = "docs_preview" if preview else "docs_batch_update"
        modules[spec.module].append(spec)

    for res_name in ("comments", "replies"):
        methods = drive.get("resources", {}).get(res_name, {}).get("methods", {})
        for method_name in sorted(methods):
            spec = build_method_tool(
                api_name="drive",
                resource_name=res_name,
                resource_attr=res_name,
                method_name=method_name,
                method=methods[method_name],
                schemas=drive_schemas,
                preview=False,
                service_type="drive",
                read_group="drive_read",
                write_group="drive",
                add_fields_param=True,
            )
            spec.module = "drive_comments"
            modules["drive_comments"].append(spec)

    files: dict[str, str] = {"__init__.py": INIT_TEMPLATE}
    for module_name, specs in modules.items():
        files[f"{module_name}.py"] = render_module(MODULE_DOCS[module_name], specs)

    manifest = {
        "service": "docs_preview",
        "tools": sorted(
            (
                {
                    "name": spec.name,
                    "module": spec.module,
                    "kind": spec.kind,
                    "source": spec.source,
                    "preview": spec.preview,
                    "read_only": spec.read_only,
                    "write_mode": spec.write_mode,
                }
                for specs in modules.values()
                for spec in specs
            ),
            key=lambda item: item["name"],
        ),
    }
    files["manifest.json"] = json.dumps(manifest, indent=2, sort_keys=True) + "\n"
    return files


def write_files(files: dict[str, str], out_dir: Path) -> list[str]:
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for name in sorted(files):
        path = out_dir / name
        content = files[name]
        if path.exists() and path.read_text(encoding="utf-8") == content:
            continue
        path.write_text(content, encoding="utf-8", newline="\n")
        written.append(name)
    return written


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--out",
        type=Path,
        default=DEFAULT_OUT_DIR,
        help=f"Output directory (default: {DEFAULT_OUT_DIR})",
    )
    args = parser.parse_args()
    files = generate()
    written = write_files(files, args.out)
    total = len(files)
    if written:
        print(f"Wrote {len(written)}/{total} files to {args.out}: {written}")
    else:
        print(f"All {total} files in {args.out} already up to date.")


if __name__ == "__main__":
    main()
