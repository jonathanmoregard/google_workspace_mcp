def wrap_block(text: str, indent: int, hanging: int | None = None) -> list[str]:
    initial = " " * indent
    subsequent = " " * (hanging if hanging is not None else indent)
    return textwrap.wrap(
        text,
        width=WIDTH,
        initial_indent=initial,
        subsequent_indent=subsequent,
        break_long_words=False,
        break_on_hyphens=False,
    ) or [initial.rstrip()]


class DocstringBuilder:
    def __init__(self, summary: str):
        self.lines: list[str] = [f'    """{summary}']

    def blank(self):
        if self.lines[-1] != "":
            self.lines.append("")

    def para(self, text: str, indent: int = 4):
        self.blank()
        self.lines.extend(wrap_block(normalize_text(text), indent))

    def section(self, title: str):
        self.blank()
        self.lines.append(f"    {title}")

    def item(self, text: str):
        self.lines.extend(wrap_block(text, 8, 12))

    def render(self) -> list[str]:
        out = list(self.lines)
        out.append('    """')
        return out


