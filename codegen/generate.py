# Fields whose descriptions are always spelled out in "Returns:" documentation
# (id/author documentation is a hard requirement for this service).
IMPORTANT_RESPONSE_FIELDS = {
    "anchor",
    "author",
    "commentId",
    "commentUpdateState",
    "id",
    "postId",
    "quotedFileContent",
    "replies",
    "resolved",
    "suggestionId",
    "suggestionResponses",
}


def snake(name: str) -> str:
    """Convert camelCase/PascalCase to snake_case."""
    out = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name)
    out = re.sub(r"(?<=[A-Z])(?=[A-Z][a-z])", "_", out)
    return out.lower()


def pascal(member: str) -> str:
    return member[0].upper() + member[1:]


def normalize_text(text: str) -> str:
    """Collapse whitespace and neutralise characters that would break docstrings."""
    text = " ".join((text or "").split())
    text = text.replace("\\", "\\\\")
    text = text.replace('"""', "'''")
    return text


def first_sentence(text: str) -> str:
    text = normalize_text(text)
    idx = text.find(". ")
    if idx != -1:
        text = text[: idx + 1]
    return text


def load_json(path: Path) -> dict:
    with open(path, encoding="utf-8") as fh:
        return json.load(fh)


def merge_overlay(base: dict, overlay: dict) -> tuple[dict, set[str], set[str]]:
    """Merge an overlay discovery fragment into a base discovery document.

    Returns (merged, preview_request_members, preview_schema_names).
    Schemas present only in the overlay are added; schemas present in both have
    their properties merged (overlay wins per property). Resource methods merge
    the same way. This works identically whether the overlay is the hand-written
    fragment or a full discovery document fetched with preview visibility.
    """
    merged = copy.deepcopy(base)
    base_request_members = set(
        base.get("schemas", {}).get("Request", {}).get("properties", {})
    )
    preview_schemas = set()

    for schema_name, schema in overlay.get("schemas", {}).items():
        target = merged.setdefault("schemas", {})
        if schema_name not in target:
            target[schema_name] = copy.deepcopy(schema)
            preview_schemas.add(schema_name)
            continue
        existing = target[schema_name]
        for prop_name, prop in schema.get("properties", {}).items():
            existing.setdefault("properties", {})[prop_name] = copy.deepcopy(prop)

    for res_name, resource in overlay.get("resources", {}).items():
        target_res = merged.setdefault("resources", {}).setdefault(res_name, {})
        for m_name, method in resource.get("methods", {}).items():
            target_res.setdefault("methods", {})[m_name] = copy.deepcopy(method)

    preview_members = (
        set(merged.get("schemas", {}).get("Request", {}).get("properties", {}))
        - base_request_members
    )
    return merged, preview_members, preview_schemas


