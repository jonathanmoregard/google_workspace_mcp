class ToolSpec:
    """Fully-resolved description of one generated tool."""

    def __init__(self, name: str):
        self.name = name
        self.title = ""
        self.kind = ""  # "method" | "batch_member"
        self.module = ""
        self.preview = False
        self.service_type = ""  # "docs" | "drive"
        self.scope_group = ""
        self.read_only = False
        self.destructive = False
        self.params: list[dict] = []  # signature order
        self.doc_lines: list[str] = []
        self.body_lines: list[str] = []
        self.imports: set[str] = set()
        self.source = ""  # e.g. "docs.documents.get" or member name
        self.write_mode = False

    def render(self) -> list[str]:
        lines = [
            "@server.tool(",
            f'    title="{self.title}",',
            "    annotations=ToolAnnotations(",
            f"        readOnlyHint={self.read_only},",
            f"        destructiveHint={self.destructive},",
            f"        idempotentHint={self.read_only},",
            "        openWorldHint=True,",
            "    ),",
            ")",
            f'@handle_http_errors("{self.name}"'
            + (", is_read_only=True" if self.read_only else "")
            + f', service_type="{self.service_type}")',
            f'@require_google_service("{self.service_type}", "{self.scope_group}")',
            f"async def {self.name}(",
            "    service: Any,",
            "    user_google_email: str,",
        ]
        for param in self.params:
            default = param.get("default_src")
            if default is None:
                lines.append(f"    {param['py_name']}: {param['annotation']},")
            else:
                lines.append(
                    f"    {param['py_name']}: {param['annotation']} = {default},"
                )
        lines.append(") -> str:")
        lines.extend(self.doc_lines)
        lines.extend(self.body_lines)
        return lines


def make_param(
    py_name: str,
    annotation: str,
    doc: str,
    wire_name: str,
    required: bool = False,
    default_src: str | None = "None",
) -> dict:
    return {
        "py_name": py_name,
        "annotation": annotation,
        "doc": doc,
        "wire_name": wire_name,
        "required": required,
        "default_src": None if required else default_src,
    }


def doc_params_section(builder: DocstringBuilder, params: list[dict]):
    builder.section("Args:")
    builder.item("user_google_email (str): The user's Google email address. Required.")
    for param in params:
        annotation = param["annotation"]
        base_type = (
            annotation[len("Optional[") : -1]
            if annotation.startswith("Optional[") and annotation.endswith("]")
            else annotation
        )
        if base_type.startswith("Literal["):
            base_type = "str"
        display = {
            "JsonDict": "dict",
            "DictList": "list[dict]",
            "StringList": "list[str]",
            "ObjectList": "list",
        }.get(base_type, base_type)
        builder.item(f"{param['py_name']} ({display}): {param['doc']}")


def enum_doc(prop: dict) -> str:
    if "enum" in prop:
        return " Values: " + " | ".join(prop["enum"]) + "."
    return ""


def ref_schema_doc(prop: dict, schemas: dict) -> str:
    """Inline one level of a referenced object schema for a dict parameter."""
    ref = prop.get("$ref") or prop.get("items", {}).get("$ref")
    if not ref or ref not in schemas:
        return ""
    fields = ", ".join(schema_fields_summary(schemas[ref]))
    return f" Object schema {ref}: {{{fields}}}."


def build_method_tool(
    api_name: str,
    resource_name: str,
    resource_attr: str,
    method_name: str,
    method: dict,
    schemas: dict,
    preview: bool,
    service_type: str,
    read_group: str,
    write_group: str,
    add_fields_param: bool,
) -> ToolSpec:
    http = method.get("httpMethod", "GET")
    read_only = http == "GET"
    tool_name = f"{api_name}_api_{resource_name}_{snake(method_name)}"
    spec = ToolSpec(tool_name)
    spec.kind = "method"
    spec.source = method.get("id", f"{resource_name}.{method_name}")
    spec.preview = preview
    spec.service_type = service_type
    spec.scope_group = read_group if read_only else write_group
    spec.read_only = read_only
    spec.destructive = http == "DELETE"
    api_title = "Docs" if service_type == "docs" else "Drive"
    spec.title = f"{api_title} API: {resource_name}.{method_name}"

    parameters = method.get("parameters", {})
    order = list(method.get("parameterOrder", []))
    required_names = [p for p in order if p in parameters]
    for extra in sorted(parameters):
        if parameters[extra].get("required") and extra not in required_names:
            required_names.append(extra)
    optional_names = sorted(p for p in parameters if p not in required_names)

    params: list[dict] = []
    for pname in required_names:
        prop = parameters[pname]
        annotation = SCALAR_TYPES.get(prop.get("type"), "str")
        doc = first_sentence(prop.get("description", "")) + enum_doc(prop)
        params.append(make_param(snake(pname), annotation, doc, pname, required=True))

    request_ref = method.get("request", {}).get("$ref")
    if request_ref:
        body_doc = (
            f"The {request_ref} request body as a dict."
            f" Pass {{}} for an empty body where the API allows it."
        )
        body_schema = schemas.get(request_ref, {})
        fields = ", ".join(schema_fields_summary(body_schema))
        if fields:
            body_doc += f" Top-level fields: {{{fields}}}."
        params.append(make_param("body", "JsonDict", body_doc, "body", required=True))

    for pname in optional_names:
        prop = parameters[pname]
        annotation, extra_imports = prop_annotation(prop)
        doc = first_sentence(prop.get("description", "")) + enum_doc(prop)
        params.append(make_param(snake(pname), annotation, doc, pname))
        spec.imports |= extra_imports

    if add_fields_param:
        params.append(
            make_param(
                "fields",
                "Optional[str]",
                "Selector specifying which fields to include in the response."
                " The Drive API requires an explicit selector for full"
                ' comment/reply payloads; the default "*" returns all fields.',
                "fields",
                default_src='"*"',
            )
        )

    spec.params = params
    if request_ref:
        spec.imports.add("JsonDict")

    marker = "[DEVELOPER PREVIEW]" if preview else "[GA]"
    method_desc = normalize_text(method.get("description", ""))
    builder = DocstringBuilder(f"{marker} {api_title} API method {spec.source}.")
    builder.para(method_desc)
    builder.para(
        f"Auto-generated 1:1 wrapper for {http} {method.get('path', '')}"
        f" ({api_title} API)."
    )
    if preview:
        builder.para(
            "Google Workspace Developer Preview: requires preview program"
            " enrollment; without it the API returns an error."
        )
    doc_params_section(builder, params)
    builder.section("Returns:")
    response_ref = method.get("response", {}).get("$ref")
    if response_ref:
        ret = f"str: JSON-serialized {response_ref}."
        response_schema = schemas.get(response_ref, {})
        fields = "; ".join(schema_fields_summary(response_schema))
        if fields:
            ret += f" Fields: {fields}."
        builder.item(ret)
    else:
        builder.item(
            "str: A fixed success message (this API method returns an empty"
            " response body)."
        )
    spec.doc_lines = builder.render()

    required_entries = [
        f'        "{param["wire_name"]}": {param["py_name"]},'
        for param in params
        if param["required"] and param["wire_name"] != "body"
    ]
    if required_entries:
        body = ["    request_kwargs: dict[str, Any] = {"]
        body.extend(required_entries)
        body.append("    }")
    else:
        body = ["    request_kwargs: dict[str, Any] = {}"]
    if request_ref:
        body.append('    request_kwargs["body"] = body')
    for param in params:
        if not param["required"]:
            body.append(f"    if {param['py_name']} is not None:")
            body.append(
                f'        request_kwargs["{param["wire_name"]}"] = {param["py_name"]}'
            )
    body.append(
        f"    api_call = service.{resource_attr}().{method_name}(**request_kwargs)"
    )
    body.append("    response = await asyncio.to_thread(api_call.execute)")
    body.append("    if not response:")
    body.append('        return "Success: the API returned an empty response."')
    body.append("    return json.dumps(response, indent=2, sort_keys=True)")
    spec.body_lines = body
    return spec


def build_member_tool(
    member: str,
    member_prop: dict,
    schemas: dict,
    preview: bool,
    write_mode_available: bool,
    config: dict,
) -> ToolSpec:
    tool_name = f"docs_api_{snake(member)}"
    spec = ToolSpec(tool_name)
    spec.kind = "batch_member"
    spec.source = member
    spec.preview = preview
    spec.service_type = "docs"
    spec.scope_group = "docs_write"
    spec.read_only = False
    spec.destructive = member.startswith("delete")
    spec.title = (
        f"Docs API Preview: {member} (batchUpdate)"
        if preview
        else f"Docs API: {member} (batchUpdate)"
    )

    request_ref = member_prop.get("$ref", pascal(member) + "Request")
    request_schema = schemas.get(request_ref, {})
    suggest_unsupported = set(config.get("suggest_mode_unsupported", []))
    partial_notes = config.get("suggest_mode_partial", {})
    spec.write_mode = write_mode_available and member not in suggest_unsupported

    params: list[dict] = [
        make_param(
            "document_id",
            "str",
            "The ID of the document to update.",
            "documentId",
            required=True,
        )
    ]
    for pname in sorted(request_schema.get("properties", {})):
        prop = request_schema["properties"][pname]
        annotation, extra_imports = prop_annotation(prop)
        doc = first_sentence(prop.get("description", "")) + enum_doc(prop)
        doc += ref_schema_doc(prop, schemas)
        params.append(make_param(snake(pname), annotation, doc, pname))
        spec.imports |= extra_imports
    if spec.write_mode:
        doc = (
            "Optional writeControl.writeMode for this batchUpdate call."
            ' Use "SUGGEST" to apply this update as a suggestion instead of a'
            " direct edit (Developer Preview; requires enrollment)."
            " Omit for a normal edit."
        )
        if member in partial_notes:
            doc += " " + normalize_text(partial_notes[member])
        params.append(
            make_param(
                "write_mode",
                'Optional[Literal["EDIT", "SUGGEST"]]',
                doc,
                "writeMode",
            )
        )
        spec.imports.add("Literal")
    spec.params = params

    marker = "[DEVELOPER PREVIEW]" if preview else "[GA]"
    builder = DocstringBuilder(f"{marker} Docs API batchUpdate request {member}.")
    builder.para(normalize_text(request_schema.get("description", "")))
    builder.para(
        f"Auto-generated wrapper that sends a single {request_ref} via"
        " POST v1/documents/{documentId}:batchUpdate."
    )
    if preview:
        builder.para(
            "Google Workspace Developer Preview: requires preview program"
            " enrollment; without it the API rejects this request type."
            " Thread/suggestion updates can partially fail even when the"
            " batch succeeds; check commentUpdateState in the response."
        )
    doc_params_section(builder, params)
    builder.section("Returns:")
    response_schema = schemas.get("BatchUpdateDocumentResponse", {})
    ret = "str: JSON-serialized BatchUpdateDocumentResponse."
    fields = "; ".join(schema_fields_summary(response_schema))
    if fields:
        ret += f" Fields: {fields}."
    builder.item(ret)
    reply_ref = pascal(member) + "Response"
    if reply_ref in schemas:
        reply_fields = "; ".join(
            schema_fields_summary(schemas[reply_ref], spell_out=True)
        )
        builder.item(
            f"The reply for this request (in replies[0]) is {reply_ref}:"
            f" {reply_fields}."
        )
        for _, nested in sorted(schemas[reply_ref].get("properties", {}).items()):
            nested_ref = nested.get("$ref")
            if nested_ref and nested_ref in schemas:
                nested_fields = "; ".join(
                    schema_fields_summary(schemas[nested_ref], spell_out=True)
                )
                builder.item(f"{nested_ref} fields: {nested_fields}.")
    spec.doc_lines = builder.render()

    body = ["    request_body: dict[str, Any] = {}"]
    for param in params:
        if param["py_name"] in ("document_id", "write_mode"):
            continue
        body.append(f"    if {param['py_name']} is not None:")
        body.append(
            f'        request_body["{param["wire_name"]}"] = {param["py_name"]}'
        )
    body.append(
        f'    body: dict[str, Any] = {{"requests": [{{"{member}": request_body}}]}}'
    )
    if spec.write_mode:
        body.append("    if write_mode is not None:")
        body.append('        body["writeControl"] = {"writeMode": write_mode}')
    body.append(
        "    api_call = service.documents().batchUpdate("
        "documentId=document_id, body=body)"
    )
    body.append("    response = await asyncio.to_thread(api_call.execute)")
    body.append("    if not response:")
    body.append('        return "Success: the API returned an empty response."')
    body.append("    return json.dumps(response, indent=2, sort_keys=True)")
    spec.body_lines = body
    return spec


