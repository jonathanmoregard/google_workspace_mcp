#!/usr/bin/env python3
"""Deterministic MCP tool-module generator for the ``docs_preview`` service.

Reads committed Google API discovery documents plus a hand-written Developer
Preview overlay and emits Python tool modules into ``gdocs_preview/generated/``.

Inputs (all committed to the repo):
  - codegen/discovery/docs-v1.json          public Docs v1 discovery
  - codegen/discovery/drive-v3.json         public Drive v3 discovery
  - codegen/overlay/docs_preview_overlay.json
        discovery-format overlay carrying the July 2026 Docs API Developer
        Preview surface (absent from public discovery). Post-enrollment this
        file is replaced by real discovery output with no generator changes.
  - codegen/overlay/generator_config.json   generator-owned metadata
        (SUGGEST-write-mode compatibility) that survives overlay replacement.

Outputs (committed; regenerate with ``python codegen/generate.py``):
  - gdocs_preview/generated/__init__.py
  - gdocs_preview/generated/docs_methods.py       documents.get/create/batchUpdate
  - gdocs_preview/generated/docs_batch_update.py  one tool per GA Request member
  - gdocs_preview/generated/docs_preview.py       one tool per preview Request member
  - gdocs_preview/generated/drive_comments.py     Drive v3 comments.* / replies.*
  - gdocs_preview/generated/manifest.json         machine-readable tool inventory

The generator is deterministic: identical inputs produce byte-identical
outputs (all iteration is sorted, no timestamps are embedded).
"""

