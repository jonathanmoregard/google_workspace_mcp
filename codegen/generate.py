def render_module(module_doc: str, specs: list[ToolSpec]) -> str:
    special = set()
    for spec in specs:
        special |= spec.imports
    lines = [GENERATED_HEADER.rstrip()]
    lines.append(module_doc)
    lines.append("")
    lines.append("import asyncio")
    lines.append("import json")
    typing_imports = ["Any"]
    if "Literal" in special:
        typing_imports.append("Literal")
    typing_imports.append("Optional")
    lines.append(f"from typing import {', '.join(typing_imports)}")
    lines.append("")
    lines.append("from mcp.types import ToolAnnotations")
    lines.append("")
    lines.append("from auth.service_decorator import require_google_service")
    lines.append("from core.server import server")
    util_imports = ["handle_http_errors"]
    for name in ("DictList", "JsonDict", "ObjectList", "StringList"):
        if name in special:
            util_imports.append(name)
    lines.append(f"from core.utils import {', '.join(sorted(util_imports))}")
    for spec in specs:
        lines.append("")
        lines.append("")
        lines.extend(spec.render())
    return "\n".join(lines) + "\n"


