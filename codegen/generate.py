SCALAR_TYPES = {
    "string": "str",
    "integer": "int",
    "number": "float",
    "boolean": "bool",
}


def prop_annotation(prop: dict) -> tuple[str, set[str]]:
    """Return (python annotation for Optional param, needed special imports)."""
    if "$ref" in prop:
        return "Optional[JsonDict]", {"JsonDict"}
    ptype = prop.get("type")
    if ptype == "object":
        return "Optional[JsonDict]", {"JsonDict"}
    if ptype == "array":
        items = prop.get("items", {})
        if "$ref" in items or items.get("type") == "object":
            return "Optional[DictList]", {"DictList"}
        if items.get("type") == "string":
            return "Optional[StringList]", {"StringList"}
        return "Optional[ObjectList]", {"ObjectList"}
    return f"Optional[{SCALAR_TYPES.get(ptype, 'str')}]", set()


def prop_type_label(prop: dict) -> str:
    """Human-readable type label for docstrings."""
    if "$ref" in prop:
        return prop["$ref"]
    ptype = prop.get("type", "any")
    if ptype == "array":
        items = prop.get("items", {})
        inner = items.get("$ref") or items.get("type", "any")
        return f"array<{inner}>"
    return ptype


def schema_fields_summary(schema: dict, spell_out: bool = False) -> list[str]:
    """One entry per top-level property: 'name (type)' with optional description."""
    entries = []
    for name in sorted(schema.get("properties", {})):
        prop = schema["properties"][name]
        label = f"{name} ({prop_type_label(prop)})"
        if spell_out or name in IMPORTANT_RESPONSE_FIELDS:
            desc = first_sentence(prop.get("description", ""))
            if desc:
                label += f": {desc}"
        entries.append(label)
    return entries


